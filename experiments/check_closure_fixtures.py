#!/usr/bin/env python3
"""Adversarial fixtures for the Closure Lemma's joint-conjunction and shared-generator contracts.

Issue #32 support for the rank-query candidate (C080, stage 4).  The compiler
under test (`rank_preimage.py`, `rank_preimage_core.py`) is imported and never
modified.  Everything used to JUDGE it is written here independently:

* `truth(G, Q)`: a brute-force evaluator of a query on a finite coloured graph
  (exhaustive assignments, breadth-first search on the (vertex, control) product);
* `extensions(I, B, max_len)`: EVERY safe first-return extension `C` of a base
  reference `B` up to a letter cap, generated by literal reverse runs and literal
  border/flag checks, not by the compiler's cursor walk;
* the two directions of the Closure Lemma are then tested for each fixture:
  completeness  - a `C` found by brute force with `P(C) ⊨ φ` must make the
                  compiled union `Pre_I(φ)` satisfiable on `P(B)`;
  soundness     - every satisfiable compiled clause must reconstruct to ONE safe
                  first-return extension whose graph satisfies `φ`.

The separate all-length oracle `rank_frontier_oracle.fixed_reference_query` is
compared where it completes.  A length cap or a work cap is UNKNOWN, never a
negative verdict.  Full compiled unions are exhausted only where the report says
so; other unions are sampled.  Standard library only; Python 3.10+.
"""
