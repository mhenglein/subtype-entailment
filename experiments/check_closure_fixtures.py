def exact(labels):
    return table(len(labels) + 1, tuple((j, a, j + 1) for j, a in enumerate(labels)),
                 final=(len(labels),))


def loop(labels):
    return table(1, [(0, a, 0) for a in labels])


def root_end(observers, source='end', target='root'):
    return Query(('root', 'end'), (('root', fld('root', True)), ('end', fld('end', True))),
                 atoms=tuple(Atom(o, source, target) for o in observers))


def joint_conjunction_fixtures(V: Verdicts, quick: bool):
    """Contract 1: separately satisfiable atoms that are jointly unsatisfiable."""
    toy = Instance(((0, 0),), frozenset())
    B = Reference('0', (0, 0))
    # The known S-length fixture: length two AND length three from root to end.
    for lengths in ((2,), (3,), (2, 3)):
        Q = Query(('r', 'e'), (('r', fld('root', True)), ('e', fld('end', True))),
                  atoms=tuple(Atom(exact(('S',) * n), 'r', 'e') for n in lengths))
        found = fixture(toy, B, Q, V, f'S-lengths {lengths}', max_len=6,
                        others=(Reference('1', (0, 0)), Reference('00', (0,) * 3)))
        expected = len(lengths) == 1
        if bool(found) != expected:
            V.discrepancies.append(dict(kind='brute_force_unexpected', fixture=f'S-lengths {lengths}'))
    # Sampled soundness of the (very large) joint union for the incompatible pair.
    Qj = Query(('r', 'e'), (('r', fld('root', True)), ('e', fld('end', True))),
               atoms=(Atom(exact(('S', 'S')), 'r', 'e'), Atom(exact(('S', 'S', 'S')), 'r', 'e')))
    status, clauses, satisfied = exhaust_union(toy, B, Qj, V, 'S-lengths sampled', work_cap=400000,
                                               require_final=False)
    V.records.append(dict(fixture='S-lengths (2,3) joint union sample', union=status,
                          compiled_clauses=clauses, satisfied_clauses=satisfied))
    if satisfied:
        V.discrepancies.append(dict(kind='joint_union_satisfied_but_no_extension', fixture='S-lengths (2,3)'))
    # Two-atom loop-observer unions on the toy: all pairs of label sets, both atoms end->root.
    subsets = [tuple(a for j, a in enumerate(LABELS) if mask >> j & 1) for mask in range(1, 16)]
    pairs = [(A, Bset) for i, A in enumerate(subsets) for Bset in subsets[i:]]
    rng = random.Random(SEED)
    rng.shuffle(pairs)
    limit = 2 if quick else 14
    bases = [Reference(w, (0,) * (len(w) + 1)) for w in ('0', '01', '10')]
    done = 0
    for A, Bset in pairs:
        if done >= limit:
            break
        Q = root_end((loop(A), loop(Bset)))
        separately = [oracle_status(toy, b, root_end((loop(x),)), False) for b in bases[:1] for x in (A, Bset)]
        jointly = oracle_status(toy, bases[0], Q, False)
        if separately == ['YES', 'YES'] and jointly == 'NO':
            V.bump('jointly_unsatisfiable_pairs')
        for b in bases[:1]:
            fixture(toy, b, Q, V, f'two-loop {A}|{Bset} base {b.word}', max_len=6, exhaust=True,
                    others=bases[1:], work_cap=None if FULL else WORK_CAP,
                    time_cap=None if FULL else UNION_SECONDS)
        done += 1
    # Shared endpoints and zero-length pieces: both atoms share the same variables and
    # one atom is an empty path at the endpoint.
    Qz = Query(('e', 'u'), (('e', fld('end', True)),), equal=(('e', 'u'),),
               atoms=(Atom(table(1, ()), 'e', 'u'), Atom(loop(('F',)), 'e', 'u')))
    fixture(toy, Reference('00', (0,) * 3), Qz, V, 'zero-length shared endpoint', max_len=5, exhaust=True,
            work_cap=None if FULL else WORK_CAP)


