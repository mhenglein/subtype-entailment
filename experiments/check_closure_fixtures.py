def check_soundness(I, B, Q, compiled, sol, V: Verdicts, tag, require_final=True):
    """A satisfied compiled clause must yield ONE safe first return satisfying Q."""
    G_B = literal_graph(I, B)
    try:
        C, assignment = reconstruct_reference(I, B, _diagram_of(compiled), compiled, sol)
    except AssertionError as exc:  # pragma: no cover - reported, never hidden
        V.discrepancies.append(dict(kind='reconstruction_failed', fixture=tag, base=B.word,
                                    error=str(exc)))
        return None
    ok = literal_first_return(B.word, C.word) and literal_safe(I, C.word, C.labels, require_final)
    ok = ok and truth(literal_graph(I, C), Q)
    ok = ok and C.word[:len(B.word)] == B.word and C.labels[:len(B.labels)] == B.labels
    if not ok:
        V.discrepancies.append(dict(kind='unsound_clause', fixture=tag, base=B.word,
                                    reconstructed=C.word, labels=list(C.labels)))
    else:
        V.bump('sound_reconstructions')
    return C


_DIAGRAMS: dict = {}


def _diagram_of(compiled):
    return _DIAGRAMS[id(compiled)]


def compiled_union(I, Q, budget):
    """Iterate compiled clauses while remembering the diagram of each."""
    from rank_preimage import iter_diagrams, InvalidDiagram
    for D in iter_diagrams(I, Q, budget):
        budget.tick()
        try:
            P = compile_diagram(I, Q, D)
        except (InvalidDiagram, KeyError):
            continue
        _DIAGRAMS[id(P)] = D
        yield P


def exhaust_union(I, B, Q, V: Verdicts, tag, work_cap=None, time_cap=None, require_final=True):
    """Evaluate EVERY compiled clause on P(B); return (status, clauses, satisfied)."""
    G_B = literal_graph(I, B)
    budget = Budget(work_cap)
    clauses = satisfied = 0
    started = time.time()
    bound = closure_bound(len(I.delta), Q.weight)
    try:
        for P in compiled_union(I, Q, budget):
            clauses += 1
            if P.weight > bound:
                V.discrepancies.append(dict(kind='clause_weight_exceeds_U_k', fixture=tag,
                                            weight=P.weight, bound=bound))
            V.bump('weight_bound_checks')
            sol = model(G_B, P, budget)
            if sol is not None:
                satisfied += 1
                check_soundness(I, B, Q, P, sol, V, tag, require_final)
            _DIAGRAMS.pop(id(P), None)
            if time_cap is not None and time.time() - started > time_cap:
                log(f'  {tag}: union time-capped after {clauses} clauses ({satisfied} satisfied)')
                return 'UNKNOWN_TIME', clauses, satisfied
    except Exhausted:
        log(f'  {tag}: union work-capped after {clauses} clauses ({satisfied} satisfied)')
        return 'UNKNOWN_WORK', clauses, satisfied
    log(f'  {tag}: union exhausted, {clauses} clauses, {satisfied} satisfied, {time.time()-started:.1f}s')
    return 'EXHAUSTED', clauses, satisfied


def completeness_certificates(I, B, Q, found, V: Verdicts, tag, others=(), require_final=True):
    """Every brute-force C with P(C) ⊨ Q gives a compiled clause true on P(B) (and
    sound on other bases where it happens to hold)."""
    G_B = literal_graph(I, B)
    for C in found:
        G_C = literal_graph(I, C)
        sol = model(G_C, Q, Budget(2000000))
        if sol is None:
            V.discrepancies.append(dict(kind='compiler_evaluator_disagrees', fixture=tag,
                                        extension=C.word))
            continue
        D = extract_diagram(I, B, C, Q, sol)
        ok, why = enumerator_accepts(I, Q, D)
        if ok:
            V.bump('certificate_diagrams_enumerated')
        else:
            V.discrepancies.append(dict(kind='certificate_diagram_not_enumerated', fixture=tag,
                                        extension=C.word, reason=why))
        P = compile_diagram(I, Q, D)
        _DIAGRAMS[id(P)] = D
        if P.weight > closure_bound(len(I.delta), Q.weight):
            V.discrepancies.append(dict(kind='clause_weight_exceeds_U_k', fixture=tag, weight=P.weight))
        V.bump('weight_bound_checks')
        base_sol = model(G_B, P, Budget(3000000))
        if base_sol is None:
            V.discrepancies.append(dict(kind='forward_direction_failed', fixture=tag,
                                        base=B.word, extension=C.word))
        else:
            V.bump('forward_certificates')
            check_soundness(I, B, Q, P, base_sol, V, tag, require_final)
            for B2 in others:
                sol2 = model(literal_graph(I, B2), P, Budget(3000000))
                if sol2 is not None:
                    C2 = check_soundness(I, B2, Q, P, sol2, V, tag + ':other-base', require_final)
                    V.bump('other_base_reconstructions')
                    if C2 is not None:
                        V.bump('other_base_changed_length', C2.word != C.word)
        _DIAGRAMS.pop(id(P), None)


def shape_signature(pieces):
    """Structural kind/label sequence of one path diagram; names are ignored."""
    return tuple((P.kind, P.label if P.kind in ('enter', 'exit', 'wrap') else '') for P in pieces)


def enumerator_shapes(I, query, D):
    """The kind/label sequences the finite enumerator offers for each atom of D."""
    from rank_preimage import path_shapes
    loc = {v: (kind, name) for v, kind, name in D.locations}
    out = []
    for ai, atom in enumerate(query.atoms):
        shapes = set()
        for sh in path_shapes(ai, atom.observer.size, loc[atom.source], loc[atom.target],
                              D.first_bit, Budget()):
            shapes.add(tuple((P.kind, P.label if P.kind in ('enter', 'exit', 'wrap') else '') for P in sh))
        out.append(shapes)
    return out


def compresses_to(offered, extracted):
    """Does deleting zero-length-capable core/forward pieces from an offered shape
    give the extracted kind/label sequence?  Portal pieces must match in order."""
    i = 0
    for piece in offered:
        if i < len(extracted) and piece == extracted[i]:
            i += 1
        elif piece[0] in ('core', 'forward'):
            continue
        else:
            return False
    return i == len(extracted)


def enumerator_accepts(I, query, D):
    """Would `iter_diagrams` produce a diagram with this structure?

    The enumerator is a product of independently enumerated components (roles,
    per-atom shapes, every weak order of the marks, all finite controls, states,
    next bits, base colours) with a few filters.  A certificate diagram extracted
    from a real solution is therefore enumerated iff each atom's kind/label
    sequence is offered by `path_shapes` (up to the zero-length core/forward
    pieces that extraction omits and the enumerator writes explicitly; the
    compiler turns those into empty-path control tests) and its mark order
    satisfies the filters.  This checks that without enumerating the union.
    """
    from rank_preimage import FIRST, LAST
    shapes = enumerator_shapes(I, query, D)
    for ai, pieces in enumerate(D.pieces):
        sig = shape_signature(pieces)
        if not any(compresses_to(offered, sig) for offered in shapes[ai]):
            return False, f'shape of atom {ai} not offered: {sig}'
    group = {name: i for i, names in enumerate(D.groups) for name in names}
    if group.get(FIRST) != 0 or group.get(LAST) != len(D.groups) - 1:
        return False, 'first/last marks misplaced'
    for pieces in D.pieces:
        for P in pieces:
            if P.kind == 'forward' and group[P.source] > group[P.target]:
                return False, 'backward forward piece'
    k = len(I.delta)
    if any(not 0 <= q < k for q in D.states):
        return False, 'state range'
    if D.next_bits[-1] != '' or any(b not in ('0', '1') for b in D.next_bits[:-1]):
        return False, 'next bits'
    if D.old_end_colour.forbidden >> D.old_end_colour.state & 1:
        return False, 'unsafe base endpoint'
    return True, ''


def oracle_status(I, B, Q, terminal, max_states=20000):
    ans = fixed_reference_query(I, B, Q, max_states=max_states, max_product_nodes=4096,
                                require_terminal=terminal)
    return ans['status']


def closure_bound(k, T):
    T = max(2, T)
    return 64 * k * T ** (2 * T + 2)


def log(message):
    print(message, file=sys.stderr, flush=True)


def fixture(I, B, Q, V: Verdicts, tag, max_len, exhaust=False, others=(), work_cap=None,
            time_cap=None):
    started = time.time()
    log(f'fixture {tag}')
    terminal = is_terminal(I) and B.labels[0] in I.final
    found = [C for C in extensions(I, B, max_len, terminal) if truth(literal_graph(I, C), Q)]
    V.bump('brute_force_extensions', sum(1 for _ in extensions(I, B, max_len, terminal)))
    oracle = oracle_status(I, B, Q, terminal)
    rec = dict(fixture=tag, base=B.word, labels=list(B.labels), atoms=len(Q.atoms),
               observer_sizes=[a.observer.size for a in Q.atoms], max_len=max_len,
               brute_force=('YES' if found else f'NONE_UP_TO_{max_len}'),
               shortest_found=(min((len(C.word) for C in found), default=None)), oracle=oracle)
    if found and oracle == 'NO':
        V.discrepancies.append(dict(kind='oracle_disagrees_with_brute_force', fixture=tag,
                                    extension=found[0].word))
    if oracle == 'YES':
        V.bump('oracle_yes')
    elif oracle == 'NO':
        V.bump('oracle_no')
    else:
        V.bump('oracle_unknown')
    completeness_certificates(I, B, Q, found[:6], V, tag, others, terminal)
    if exhaust:
        status, clauses, satisfied = exhaust_union(I, B, Q, V, tag, work_cap, time_cap, terminal)
        rec.update(union=status, compiled_clauses=clauses, satisfied_clauses=satisfied)
        if status == 'EXHAUSTED':
            V.bump('exhausted_unions')
            V.bump('exhausted_clauses', clauses)
            compiled_yes = satisfied > 0
            if oracle in ('YES', 'NO') and compiled_yes != (oracle == 'YES'):
                V.discrepancies.append(dict(kind='union_disagrees_with_oracle', fixture=tag,
                                            oracle=oracle, satisfied=satisfied))
            if found and not compiled_yes:
                V.discrepancies.append(dict(kind='union_misses_brute_force_extension',
                                            fixture=tag, extension=found[0].word))
        elif status == 'UNKNOWN_TIME':
            V.bump('time_capped_unions')
            V.discrepancies.append(dict(kind='nondeterministic_time_cap', fixture=tag,
                                        note='rerun with --full or a larger work cap; time caps are not reproducible'))
        else:
            V.bump('work_capped_unions')
    log(f'  {tag}: done in {time.time() - started:.1f}s')
    V.records.append(rec)
    return found


