def accepts(G: Graph, observer, source: int, target: int) -> bool:
    """Breadth-first search on (vertex, control); no reuse of the compiler's `path`."""
    out = {}
    for u, a, v in G.edges:
        out.setdefault(u, []).append((a, v))
    colours = G.colours
    seen = set()
    todo = deque()
    for q in observer.initial:
        if observer.allows(q, colours[source]):
            seen.add((source, q))
            todo.append((source, q))
    while todo:
        v, q = todo.popleft()
        if v == target and q in observer.final:
            return True
        for a, w in out.get(v, ()):
            for p in observer.move(q, a, colours[v], colours[w]):
                if observer.allows(p, colours[w]) and (w, p) not in seen:
                    seen.add((w, p))
                    todo.append((w, p))
    return False


def truth(G: Graph, Q: Query) -> bool:
    n = len(G.colours)
    domains = []
    for v in Q.variables:
        tests = [t for w, t in Q.tests if w == v]
        domains.append([i for i in range(n) if all(t.holds(G.colours[i]) for t in tests)])
    for values in product(*domains):
        d = dict(zip(Q.variables, values))
        if any(d[x] != d[y] for x, y in Q.equal):
            continue
        if any(d[x] == d[y] for x, y in Q.unequal):
            continue
        if all(accepts(G, a.observer, d[a.source], d[a.target]) for a in Q.atoms):
            return True
    return False


def literal_safe(I: Instance, rho: str, labels, require_final: bool = True) -> bool:
    """Literal border-chain safety of a reversed labelled path (no prefix function).

    `require_final=False` is the graph-mechanism mode of the compiler tests: the
    one-state toy has no accepting state, and its references are not terminal
    witness suffixes.  The terminal theorem's fixtures keep the default."""
    if len(labels) != len(rho) + 1 or (require_final and labels[0] not in I.final):
        return False
    if any(q in I.bad for q in labels):
        return False
    if any(I.delta[labels[j + 1]][int(a)] != labels[j] for j, a in enumerate(rho)):
        return False
    for j in range(len(rho) + 1):
        prefix = rho[:j]
        for b in range(j + 1):
            if prefix.endswith(rho[:b]) and (labels[j], labels[b]) in I.flags:
                return False
    return True


def literal_first_return(B: str, C: str) -> bool:
    return len(C) > len(B) > 0 and C.startswith(B) and C.find(B, 1) == len(C) - len(B)


def extensions(I: Instance, B: Reference, max_len: int, require_final: bool = True):
    """All safe first-return extensions of B with at most max_len new letters."""
    m = len(B.word)
    incoming = {}
    for p, row in enumerate(I.delta):
        for a, q in enumerate(row):
            if q >= 0:
                incoming.setdefault((q, str(a)), []).append(p)
    stack = [(B.word, B.labels)]
    while stack:
        word, labels = stack.pop()
        if len(word) - m >= max_len:
            continue
        for a in '01':
            for p in incoming.get((labels[-1], a), ()):
                new_word, new_labels = word + a, labels + (p,)
                if not literal_safe(I, new_word, new_labels, require_final):
                    continue
                hit = new_word.find(B.word, 1)
                if hit >= 0 and hit + m < len(new_word):
                    continue  # a complete earlier return already happened
                if hit >= 0 and hit + m == len(new_word):
                    yield Reference(new_word, new_labels)
                else:
                    stack.append((new_word, new_labels))


def is_terminal(I: Instance) -> bool:
    return all(t < 0 for f in I.final for t in I.delta[f])


@dataclass
class Verdicts:
    counts: Counter
    discrepancies: list
    records: list

    def bump(self, key, n=1):
        self.counts[key] += n


