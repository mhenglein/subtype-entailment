#!/usr/bin/env python3
"""Check manuscript declaration links and literal worked examples; no Lean replay."""
import argparse
import hashlib
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT / "paper"


def declaration_line(module, name):
    path = ROOT / "lean" / "Subtail" / (module + ".lean")
    pattern = re.compile(r"\b(?:theorem|def|abbrev|structure|inductive)\s+" + re.escape(name) + r"\b")
    for i, line in enumerate(path.read_text().splitlines(), 1):
        if pattern.search(line):
            return path, i
    raise ValueError(f"Missing declaration: {module}.{name}")


def render_map(data):
    lines = ["# Paper-to-Lean declaration map", "",
             "Generated from `lean-map.json` by `python3 paper/check.py --write`.", "",
             f"Default mathematical source checkpoint: `{data['source_revision']}`.",
             "Each result's links use its explicitly recorded revision; later finite-tree and explicit-top results retain their own pins.",
             "The manuscript gives ordinary proofs; this map identifies checked dependencies.",
             "A source/link check is not a new kernel replay or an independent mathematical review.", "",
             "| Paper result | Statement | Definitions and declarations |", "|---|---|---|"]
    hashes = {}
    for row in data["entries"]:
        refs = []
        revision = row.get("source_revision", data["source_revision"])
        if re.fullmatch(r"[0-9a-f]{40}", revision) is None:
            raise ValueError(f"Expected an immutable full source revision: {revision}")
        for module, name in row["declarations"]:
            path, line = declaration_line(module, name)
            rel = path.relative_to(ROOT).as_posix()
            pinned = subprocess.run(["git", "show", f"{revision}:{rel}"], cwd=ROOT,
                                    check=True, capture_output=True).stdout
            if pinned != path.read_bytes():
                raise ValueError(f"Source drift from pinned revision: {rel}; review before changing the map pin")
            hashes[rel] = hashlib.sha256(pinned).hexdigest()
            url = f"https://github.com/mhenglein/subtail/blob/{revision}/{rel}#L{line}"
            refs.append(f"[{module}.{name}]({url})")
        lines.append(f"| {row['id']} | {row['statement']} | {'; '.join(refs)} |")
    lines += ["", "## Ordinary consequences", "",
              "These results have ordinary proofs in the manuscript; they are not new Lean declarations.", "",
              "| Paper result | Statement | Earlier proof record |", "|---|---|---|"]
    for row in data.get("ordinary_results", []):
        if not (PAPER / row["evidence"]).is_file():
            raise ValueError(f"Missing ordinary-proof record: {row['evidence']}")
        lines.append(f"| {row['id']} | {row['statement']} | [Record]({row['evidence']}) |")
    lines += ["", "## Source identities", "", "These hashes let a reader detect source drift from the mapped checkpoint.", "", "```text"]
    lines += [f"{value}  {key}" for key, value in sorted(hashes.items())]
    lines += ["```", "", "The stronger numerical conjunct of `RankQuery.ClosureFor` is deliberately", "not a premise of Theorems 7.1, 9.2 or 1.1, or Lemma 9.1. A conditional theorem referring to it", "does not establish the concrete compiler's old numerical bound.", ""]
    lines += ["Theorem 13.3 is assembled from the listed checked obstruction and bounded-transfer",
              "branches; Theorem 1.2 maps directly to the final finite-expression Boolean theorem.",
              "The displayed estimate (13.2) is an ordinary derivation from the minimum-stack",
              "factorization and Lemma 13.1, not a separately exported numerical Lean theorem.", ""]
    lines += ["Explicit-top Lemmas 14.2 and 14.3 map to arbitrary predicate-language statements.",
              "Lemma 14.1 and Theorem 14.4 remain ordinary proofs: no complete labelled-tree",
              "expression compiler or native explicit-top decision is claimed by this map.", ""]
    return "\n".join(lines)


def imports(module, visited):
    if module in visited:
        return
    path = ROOT / "lean" / (module.replace(".", "/") + ".lean")
    if not path.exists():
        raise ValueError(f"Missing module {module}")
    direct = re.findall(r"^import (Subtail(?:\.[A-Za-z0-9_]+)+)\s*$", path.read_text(), re.M)
    visited[module] = direct
    for dep in direct:
        imports(dep, visited)


def render_imports():
    visited = {}
    imports("Subtail.EntailmentDecision", visited)
    arbitrary_count = len(visited)
    imports("Subtail.FiniteTreeDecision", visited)
    lines = ["# Arbitrary- and finite-tree source import closure", "", "Generated by `python3 paper/check.py --write` from the current checked-source files.", "",
             "This is a module import graph, not a theorem-dependency or axiom audit.",
             "Some modules also contain unused conditional quantitative theorems; importing", "them does not add their hypotheses to C081. Use the declaration audits for that.", "",
             f"The arbitrary-tree entry point reaches {arbitrary_count} Subtail source modules.",
             f"The union with the finite-tree entry point reaches {len(visited)} modules (including both entry points).", "",
             "| Module | Direct Subtail imports |", "|---|---|"]
    for module, deps in sorted(visited.items()):
        links = [f"[{d.removeprefix('Subtail.')}]({ '../lean/' + d.replace('.', '/') + '.lean'})" for d in deps]
        lines.append(f"| [{module.removeprefix('Subtail.')}]({'../lean/' + module.replace('.', '/') + '.lean'}) | {'; '.join(links) or 'None'} |")
    return "\n".join(lines) + "\n"


def literal_examples():
    # Direct prefix/suffix definitions; no optimized experiment implementation.
    def borders(w):
        return [j for j in range(len(w) + 1) if w[:j] == w[len(w)-j:]]
    def kmp(pattern, j, bit):
        word = pattern[:j] + bit
        return max(h for h in range(len(pattern) + 1) if word.endswith(pattern[:h]))
    assert len(borders("000")) - 1 == 3
    assert len(borders("0001")) - 1 == 1
    assert borders("00") == [0, 1, 2]
    assert kmp("00", 2, "0") == 2  # single fresh vertex wraps to itself
    assert kmp("00", 2, "1") == 0
    assert kmp("00", 1, "0") == 2
    states = ["s", "p", "f"]
    transition = {("s", "0"): "p", ("p", "0"): "f"}
    assert [transition[(states[i], "0")] for i in (0, 1)] == states[1:]
    assert not any(q == "f" for q, _ in transition)
    assert all(borders("0" * j) == list(range(j + 1)) for j in range(4))
    x, y = set(), {""}
    def product(a, b):
        return {""} | {"0" + w for w in a} | {"1" + w for w in b}
    assert x <= y
    assert product(x, set()) == {""}
    assert product(y, set()) == {"", "0"}
    assert not product(y, set()) <= product(x, set())
    # The two-observer diagram: derive edges from literal prefix/suffix matches.
    reference, extended = "0", "010"
    labels = ["f", "p", "q", "s"]
    delta = {("p", "0"): "f", ("q", "1"): "p", ("s", "0"): "q"}
    assert all(delta[(labels[j+1], bit)] == labels[j] for j, bit in enumerate(extended))
    assert [j for j in range(2, 4) if extended[:j].endswith(reference)] == [3]
    origin_first = kmp(reference, 0, "1")
    origin_last = kmp(reference, origin_first, "0")
    assert (origin_first, origin_last) == (0, 1)
    assert kmp(extended, 2, "0") == 3  # K0 and successor share the same edge
    assert kmp(extended, 2, "1") == 0
    start, end = ("q", "0", False, 0, 0), ("s", None, True, 1, 1)
    assert delta[(end[0], start[1])] == start[0]
    def permits(label, bit):
        return label == "S" or label == "K" + bit
    assert all(permits(label, start[1]) for label in ("S", "K0"))
    assert not all(permits(label, start[1]) for label in ("S", "K1"))
    # Section 13: literal finite trees and the displayed no-growth UNSAT input.
    assert not product(x, x) <= set()  # a product root cannot satisfy a denial
    reverse_edges = {("b", "0", "x"), ("b", "1", "x")}
    assert not any(source == "x" for source, _, _ in reverse_edges)
    assert product(set(), set()) == {""}
    # The finite prefix of the spine always requires one extra left address.
    for height in range(8):
        spine_prefix = {"0" * j for j in range(height)}
        assert not product(spine_prefix, set()) <= spine_prefix


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="Regenerate declaration/import maps")
    args = parser.parse_args()
    data = json.loads((PAPER / "lean-map.json").read_text())
    outputs = {"lean-map.md": render_map(data), "imports.md": render_imports()}
    for name, expected in outputs.items():
        dest = PAPER / name
        if args.write:
            dest.write_text(expected)
        elif not dest.exists() or dest.read_text() != expected:
            raise SystemExit(f"Stale map {dest}; run python3 paper/check.py --write and review drift")
    manuscript = (PAPER / "manuscript.md").read_text()
    for entry in data["entries"] + data.get("ordinary_results", []):
        declaration = r"\*\*" + re.escape(entry["id"]) + r"(?:[.(]| \()"
        if len(re.findall(declaration, manuscript)) != 1:
            raise ValueError(f"Expected one stated paper result: {entry['id']}")
    bibliography = (PAPER / "references.bib").read_text()
    keys = re.findall(r"@[A-Za-z]+\{([^,]+),", bibliography)
    if len(keys) != len(set(keys)):
        raise ValueError("Duplicate bibliography key")
    cited = set(re.findall(r"@([A-Za-z][A-Za-z0-9]+)", manuscript))
    if cited != set(keys):
        raise ValueError(f"Bibliography mismatch: missing={cited-set(keys)}, unused={set(keys)-cited}")
    for pattern in (r"\b[ACQ]0\d{2}\b", r"\bP\d+\b", r"/issues/", r"/commit/",
                    r"(?i)licensing|workflow|checkpoint|internal note|\bClosureFor\b"):
        if re.search(pattern, manuscript):
            raise ValueError(f"Internal research administration in manuscript: {pattern}")
    literal_examples()
    print(f"PASS: {len(data['entries'])} mapped results, {len(data.get('ordinary_results', []))} ordinary results, source maps, bibliography and literal examples")
    print("Lean build/kernel replay: NOT RUN by this documentation check")


if __name__ == "__main__":
    main()
