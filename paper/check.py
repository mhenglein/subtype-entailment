#!/usr/bin/env python3
"""Check manuscript declaration links and literal worked examples; no Lean replay."""
import argparse
import hashlib
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT / "paper"


def declaration_line(module, name):
    path = ROOT / "lean" / "Subtail" / (module + ".lean")
    pattern = re.compile(r"\b(?:theorem|def|abbrev|structure|inductive)\s+" + re.escape(name) + r"\b")
    for i, line in enumerate(path.read_text().splitlines(), 1):
        if pattern.search(line):
            return path, i
    raise ValueError(f"Missing declaration: {module}.{name}")


def render_map(data):
    lines = ["# Paper-to-Lean declaration map", "",
             "Generated from `lean-map.json` by `python3 paper/check.py --write`.", "",
             f"Mathematical source checkpoint: `{data['source_revision']}`. Links pin that revision.",
             "The manuscript gives ordinary proofs; this map identifies checked dependencies.",
             "A source/link check is not a new kernel replay or an independent mathematical review.", "",
             "| Paper result | Statement | Definitions and declarations |", "|---|---|---|"]
    hashes = {}
    for row in data["entries"]:
        refs = []
        for module, name in row["declarations"]:
            path, line = declaration_line(module, name)
            rel = path.relative_to(ROOT).as_posix()
            pinned = subprocess.run(["git", "show", f"{data['source_revision']}:{rel}"], cwd=ROOT,
                                    check=True, capture_output=True).stdout
            if pinned != path.read_bytes():
                raise ValueError(f"Source drift from pinned revision: {rel}; review before changing the map pin")
            hashes[rel] = hashlib.sha256(pinned).hexdigest()
            url = f"https://github.com/mhenglein/subtail/blob/{data['source_revision']}/{rel}#L{line}"
            refs.append(f"[{module}.{name}]({url})")
        lines.append(f"| {row['id']} | {row['statement']} | {'; '.join(refs)} |")
    lines += ["", "## Source identities", "", "These hashes let a reader detect source drift from the mapped checkpoint.", "", "```text"]
    lines += [f"{value}  {key}" for key, value in sorted(hashes.items())]
    lines += ["```", "", "The stronger numerical conjunct of `RankQuery.ClosureFor` is deliberately", "not a premise of P11, P13, P14 or P1. A conditional theorem referring to it", "does not establish the concrete compiler's old numerical bound.", ""]
    return "\n".join(lines)


def imports(module, visited):
    if module in visited:
        return
    path = ROOT / "lean" / (module.replace(".", "/") + ".lean")
    if not path.exists():
        raise ValueError(f"Missing module {module}")
    direct = re.findall(r"^import (Subtail(?:\.[A-Za-z0-9_]+)+)\s*$", path.read_text(), re.M)
    visited[module] = direct
    for dep in direct:
        imports(dep, visited)


def render_imports():
    visited = {}
    imports("Subtail.EntailmentDecision", visited)
    lines = ["# C081 source import closure", "", "Generated by `python3 paper/check.py --write` from the current checked-source files.", "",
             "This is a module import graph, not a theorem-dependency or axiom audit.",
             "Some modules also contain unused conditional quantitative theorems; importing", "them does not add their hypotheses to C081. Use the declaration audits for that.", "",
             f"The final module reaches {len(visited)} Subtail source modules (including itself).", "",
             "| Module | Direct Subtail imports |", "|---|---|"]
    for module, deps in sorted(visited.items()):
        links = [f"[{d.removeprefix('Subtail.')}]({ '../lean/' + d.replace('.', '/') + '.lean'})" for d in deps]
        lines.append(f"| [{module.removeprefix('Subtail.')}]({'../lean/' + module.replace('.', '/') + '.lean'}) | {'; '.join(links) or 'None'} |")
    return "\n".join(lines) + "\n"


def literal_examples():
    # Direct prefix/suffix definitions; no optimized experiment implementation.
    def borders(w):
        return [j for j in range(len(w) + 1) if w[:j] == w[len(w)-j:]]
    def kmp(pattern, j, bit):
        word = pattern[:j] + bit
        return max(h for h in range(len(pattern) + 1) if word.endswith(pattern[:h]))
    assert len(borders("000")) - 1 == 3
    assert len(borders("0001")) - 1 == 1
    assert borders("00") == [0, 1, 2]
    assert kmp("00", 2, "0") == 2  # single fresh vertex wraps to itself
    assert kmp("00", 2, "1") == 0
    assert kmp("00", 1, "0") == 2
    states = ["s", "p", "f"]
    transition = {("s", "0"): "p", ("p", "0"): "f"}
    assert [transition[(states[i], "0")] for i in (0, 1)] == states[1:]
    assert not any(q == "f" for q, _ in transition)
    assert all(borders("0" * j) == list(range(j + 1)) for j in range(4))
    x, y = set(), {""}
    def product(a, b):
        return {""} | {"0" + w for w in a} | {"1" + w for w in b}
    assert x <= y
    assert product(x, set()) == {""}
    assert product(y, set()) == {"", "0"}
    assert not product(y, set()) <= product(x, set())
    # The two-observer diagram: derive edges from literal prefix/suffix matches.
    reference, extended = "0", "010"
    labels = ["f", "p", "q", "s"]
    delta = {("p", "0"): "f", ("q", "1"): "p", ("s", "0"): "q"}
    assert all(delta[(labels[j+1], bit)] == labels[j] for j, bit in enumerate(extended))
    assert [j for j in range(2, 4) if extended[:j].endswith(reference)] == [3]
    origin_first = kmp(reference, 0, "1")
    origin_last = kmp(reference, origin_first, "0")
    assert (origin_first, origin_last) == (0, 1)
    assert kmp(extended, 2, "0") == 3  # K0 and successor share the same edge
    assert kmp(extended, 2, "1") == 0
    start, end = ("q", "0", False, 0, 0), ("s", None, True, 1, 1)
    assert delta[(end[0], start[1])] == start[0]
    def permits(label, bit):
        return label == "S" or label == "K" + bit
    assert all(permits(label, start[1]) for label in ("S", "K0"))
    assert not all(permits(label, start[1]) for label in ("S", "K1"))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="Regenerate declaration/import maps")
    args = parser.parse_args()
    data = json.loads((PAPER / "lean-map.json").read_text())
    outputs = {"lean-map.md": render_map(data), "imports.md": render_imports()}
    for name, expected in outputs.items():
        dest = PAPER / name
        if args.write:
            dest.write_text(expected)
        elif not dest.exists() or dest.read_text() != expected:
            raise SystemExit(f"Stale map {dest}; run python3 paper/check.py --write and review drift")
    manuscript = (PAPER / "manuscript.md").read_text()
    for entry in data["entries"]:
        if not re.search(r"\b" + entry["id"] + r"\b", manuscript):
            raise ValueError(f"Unreferenced paper result {entry['id']}")
    literal_examples()
    print(f"PASS: {len(data['entries'])} paper results, declaration/source maps and literal worked examples")
    print("Lean build/kernel replay: NOT RUN by this documentation check")


if __name__ == "__main__":
    main()
